class_weights = torch.tensor(
    [1.0 / cnt[i] for i in range(len(classes))],
    device=device
)

criterion = nn.CrossEntropyLoss(weight=class_weights)

optimizer = torch.optim.AdamW(
    model.parameters(),
    lr=2e-4,
    weight_decay=1e-4
)

scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(
    optimizer, T_max=25
)

scaler = torch.cuda.amp.GradScaler()

# =========================================================
# 8️⃣ TRAINING
# =========================================================
EPOCHS = 25
best_val = 0

train_acc_hist, val_acc_hist = [], []
train_loss_hist, val_loss_hist = [], []
lr_hist = []

for epoch in range(EPOCHS):
    model.train()
    tp, ty = [], []
    running_loss = 0.0

    for x, y in tqdm(train_dl, desc=f"Epoch {epoch+1}/{EPOCHS}"):
        x, y = x.to(device), y.to(device)
        optimizer.zero_grad()

        with torch.cuda.amp.autocast():
            out = model(x)
            loss = criterion(out, y)

        scaler.scale(loss).backward()
        scaler.step(optimizer)
        scaler.update()

        running_loss += loss.item()
        tp += out.argmax(1).cpu().tolist()
        ty += y.cpu().tolist()

    scheduler.step()
    lr_hist.append(optimizer.param_groups[0]["lr"])

    train_loss = running_loss / len(train_dl)
    tr_acc = accuracy_score(ty, tp)

    # -------- VALIDATION --------
    model.eval()
    vp, vy = [], []
    val_running_loss = 0.0

    with torch.no_grad():
        for x, y in val_dl:
            x, y = x.to(device), y.to(device)
            out = model(x)
            loss = criterion(out, y)

            val_running_loss += loss.item()
            vp += out.argmax(1).cpu().tolist()
            vy += y.cpu().tolist()

    val_loss = val_running_loss / len(val_dl)
    v_acc = accuracy_score(vy, vp)

    train_acc_hist.append(tr_acc)
    val_acc_hist.append(v_acc)
    train_loss_hist.append(train_loss)
    val_loss_hist.append(val_loss)

    print(
        f"📊 Epoch {epoch+1}: "
        f"Train Acc={tr_acc:.4f} | Val Acc={v_acc:.4f} | "
        f"Train Loss={train_loss:.4f} | Val Loss={val_loss:.4f}"
    )

    if v_acc > best_val:
        best_val = v_acc
        torch.save(model.state_dict(), "Best_EfficientNetV2S.pth")
        print("✅ Best model saved")

